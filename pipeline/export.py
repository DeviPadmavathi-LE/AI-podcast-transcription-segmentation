"""
TALK2TOPICS — Export Pipeline
Generates downloadable files from processed podcast data.
Formats: txt, json, srt, md, csv
"""

import os
import json
import csv
import logging
import tempfile

log = logging.getLogger('talk2topics.export')

EXPORT_DIR = "outputs/exports"
os.makedirs(EXPORT_DIR, exist_ok=True)


def generate_export(data: dict, fmt: str, job_id: str) -> tuple:
    """
    Generate a downloadable file for the given format.

    Args:
        data:   The full pipeline payload dict.
        fmt:    One of: txt, json, srt, md, csv
        job_id: Used to name the temp file.

    Returns:
        (file_path: str, mime_type: str)

    Raises:
        ValueError: If format is unsupported.
    """
    generators = {
        'txt':  (_generate_txt,  'text/plain'),
        'json': (_generate_json, 'application/json'),
        'srt':  (_generate_srt,  'text/plain'),
        'md':   (_generate_md,   'text/markdown'),
        'csv':  (_generate_csv,  'text/csv'),
    }

    if fmt not in generators:
        raise ValueError(f"Unsupported format '{fmt}'. Choose from: {', '.join(generators)}")

    generator_fn, mime_type = generators[fmt]
    out_path = os.path.join(EXPORT_DIR, f"{job_id[:8]}_{fmt}.{fmt}")

    content = generator_fn(data)

    with open(out_path, 'w', encoding='utf-8') as f:
        f.write(content)

    log.info(f"Export generated: {out_path}")
    return out_path, mime_type


# ─────────────────────────────────────────────
# Format Generators
# ─────────────────────────────────────────────

def _generate_txt(data: dict) -> str:
    """Plain text transcript with timestamps."""
    lines = ["TALK2TOPICS — Full Transcript", "=" * 50, ""]

    meta = data.get('metadata', {})
    lines.append(f"File:        {data.get('original_filename', 'Unknown')}")
    lines.append(f"Duration:    {meta.get('duration_str', 'N/A')}")
    lines.append(f"Words:       {meta.get('word_count', 0)}")
    lines.append(f"Topics:      {meta.get('topic_count', 0)}")
    lines.append(f"Processed:   {meta.get('processed_at', 'N/A')}")
    lines.append("")
    lines.append("─" * 50)
    lines.append("EXECUTIVE SUMMARY")
    lines.append("─" * 50)
    lines.append(data.get('executive_summary', ''))
    lines.append("")
    lines.append("─" * 50)
    lines.append("FULL TRANSCRIPT")
    lines.append("─" * 50)
    lines.append("")

    for seg in data.get('transcript', []):
        start = _fmt_sec(seg.get('start', 0))
        end   = _fmt_sec(seg.get('end', 0))
        lines.append(f"[{start} → {end}]")
        lines.append(seg.get('text', ''))
        lines.append("")

    return "\n".join(lines)


def _generate_json(data: dict) -> str:
    """Full structured JSON."""
    return json.dumps(data, indent=2, ensure_ascii=False)


def _generate_srt(data: dict) -> str:
    """SubRip subtitle format (.srt)."""
    lines = []
    for i, seg in enumerate(data.get('transcript', []), start=1):
        start = _srt_time(seg.get('start', 0))
        end   = _srt_time(seg.get('end', 0))
        text  = seg.get('text', '').strip()
        lines.append(str(i))
        lines.append(f"{start} --> {end}")
        lines.append(text)
        lines.append("")
    return "\n".join(lines)


def _generate_md(data: dict) -> str:
    """Markdown document with headings per topic."""
    lines = [
        f"# {data.get('original_filename', 'Podcast Transcript')}",
        "",
        "> Generated by **TALK2TOPICS** AI",
        "",
        "## Executive Summary",
        "",
        data.get('executive_summary', '*No summary available.*'),
        "",
        "---",
        "",
        "## Topics",
        "",
    ]

    for topic in data.get('topics', []):
        start = _fmt_sec(topic.get('start', 0))
        end   = _fmt_sec(topic.get('end', 0))
        title = topic.get('title', f"Topic {topic.get('id', 0) + 1}")
        lines.append(f"### {title}  `{start} – {end}`")
        lines.append("")
        kws = topic.get('keywords', [])
        if kws:
            lines.append("**Keywords:** " + " · ".join(f"`{k}`" for k in kws))
            lines.append("")
        lines.append(topic.get('summary', ''))
        lines.append("")
        lines.append("> " + topic.get('text', '').replace('\n', '\n> '))
        lines.append("")
        lines.append("---")
        lines.append("")

    lines.append("## Full Transcript")
    lines.append("")
    for seg in data.get('transcript', []):
        start = _fmt_sec(seg.get('start', 0))
        end   = _fmt_sec(seg.get('end', 0))
        lines.append(f"**[{start} → {end}]** {seg.get('text', '')}")
        lines.append("")

    return "\n".join(lines)


def _generate_csv(data: dict) -> str:
    """CSV table of topics with metadata."""
    import io
    buf = io.StringIO()
    writer = csv.writer(buf)
    writer.writerow(["ID", "Start", "End", "Title", "Summary", "Keywords", "Sentiment", "Score"])

    for topic in data.get('topics', []):
        sentiment = topic.get('sentiment', {})
        writer.writerow([
            topic.get('id', ''),
            _fmt_sec(topic.get('start', 0)),
            _fmt_sec(topic.get('end', 0)),
            topic.get('title', ''),
            topic.get('summary', ''),
            "; ".join(topic.get('keywords', [])),
            sentiment.get('label', ''),
            sentiment.get('score', ''),
        ])

    return buf.getvalue()


# ─────────────────────────────────────────────
# Time Formatting Helpers
# ─────────────────────────────────────────────

def _fmt_sec(sec: float) -> str:
    sec = int(sec)
    m = sec // 60
    s = sec % 60
    return f"{m}:{s:02d}"


def _srt_time(sec: float) -> str:
    """Format seconds as HH:MM:SS,mmm for SRT."""
    ms = int((sec % 1) * 1000)
    sec = int(sec)
    h  = sec // 3600
    m  = (sec % 3600) // 60
    s  = sec % 60
    return f"{h:02d}:{m:02d}:{s:02d},{ms:03d}"
